CREATE TABLE public.journal_entries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  entry_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  slug text NOT NULL UNIQUE
    CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$' AND char_length(slug) <= 120),
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 180),
  excerpt text CHECK (char_length(excerpt) <= 500),
  entry_type public.journal_entry_type NOT NULL DEFAULT 'journal',
  status public.journal_status NOT NULL DEFAULT 'draft',
  content jsonb NOT NULL DEFAULT '{"version":1,"blocks":[]}'::jsonb
    CHECK (
      jsonb_typeof(content) = 'object'
      AND content ->> 'version' = '1'
      AND jsonb_typeof(content -> 'blocks') = 'array'
    ),
  event_date date,
  location text CHECK (char_length(location) <= 160),
  published_at timestamptz,
  featured_at timestamptz,
  seo_title text CHECK (char_length(seo_title) <= 70),
  seo_description text CHECK (char_length(seo_description) <= 180),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (status NOT IN ('published', 'scheduled') OR published_at IS NOT NULL),
  CHECK (featured_at IS NULL OR status = 'published')
);

CREATE TABLE public.journal_media (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  entry_id uuid NOT NULL REFERENCES public.journal_entries(id) ON DELETE CASCADE,
  storage_path text NOT NULL UNIQUE
    CHECK (storage_path ~ '^[0-9a-f-]{36}/[A-Za-z0-9._-]+$' AND char_length(storage_path) <= 500),
  kind public.journal_media_kind NOT NULL DEFAULT 'image',
  mime_type text NOT NULL CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp', 'image/avif', 'video/mp4')),
  width integer CHECK (width IS NULL OR width > 0),
  height integer CHECK (height IS NULL OR height > 0),
  file_size_bytes bigint CHECK (file_size_bytes IS NULL OR file_size_bytes > 0),
  blur_data_url text CHECK (char_length(blur_data_url) <= 1000),
  alt_text text CHECK (char_length(alt_text) <= 500),
  caption text CHECK (char_length(caption) <= 1000),
  credit text CHECK (char_length(credit) <= 300),
  sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT journal_media_entry_sort_unique
    UNIQUE (entry_id, sort_order) DEFERRABLE INITIALLY DEFERRED
);

