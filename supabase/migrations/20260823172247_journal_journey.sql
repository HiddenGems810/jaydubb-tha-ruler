CREATE OR REPLACE FUNCTION public.validate_journal_publication()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
BEGIN
  IF NEW.status = 'scheduled'
    AND NEW.published_at <= now()
    AND (
      TG_OP = 'INSERT'
      OR OLD.status IS DISTINCT FROM 'scheduled'
      OR OLD.published_at IS DISTINCT FROM NEW.published_at
    )
  THEN
    RAISE EXCEPTION 'Scheduled publication time must be in the future' USING ERRCODE = '23514';
  END IF;

  IF NEW.status IN ('published', 'scheduled') AND EXISTS (
    SELECT 1
    FROM public.journal_media media
    WHERE media.entry_id = NEW.id
      AND media.kind = 'image'
      AND coalesce(btrim(media.alt_text), '') = ''
  ) THEN
    RAISE EXCEPTION 'Every published Journal image requires alt text' USING ERRCODE = '23514';
  END IF;

  IF NEW.cover_media_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.journal_media media
    WHERE media.id = NEW.cover_media_id AND media.entry_id = NEW.id
  ) THEN
    RAISE EXCEPTION 'Cover media must belong to the same Journal entry' USING ERRCODE = '23514';
  END IF;

  IF NEW.og_media_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.journal_media media
    WHERE media.id = NEW.og_media_id AND media.entry_id = NEW.id
  ) THEN
    RAISE EXCEPTION 'Open Graph media must belong to the same Journal entry' USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER tr_validate_journal_publication
  BEFORE INSERT OR UPDATE OF status, published_at, cover_media_id, og_media_id ON public.journal_entries
  FOR EACH ROW EXECUTE FUNCTION public.validate_journal_publication();

CREATE OR REPLACE FUNCTION public.validate_journal_media_alt()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
BEGIN
  IF NEW.kind = 'image'
    AND coalesce(btrim(NEW.alt_text), '') = ''
    AND EXISTS (
      SELECT 1 FROM public.journal_entries entry
      WHERE entry.id = NEW.entry_id
        AND entry.status IN ('published', 'scheduled')
    )
  THEN
    RAISE EXCEPTION 'Every published Journal image requires alt text' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER tr_validate_journal_media_alt
  BEFORE INSERT OR UPDATE OF kind, alt_text, entry_id ON public.journal_media
  FOR EACH ROW EXECUTE FUNCTION public.validate_journal_media_alt();

CREATE OR REPLACE FUNCTION public.set_featured_journal_entry(target_id uuid)
RETURNS public.journal_entries
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  selected_entry public.journal_entries;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Administrator access required' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO selected_entry
  FROM public.journal_entries
  WHERE id = target_id
  FOR UPDATE;

  IF selected_entry.id IS NULL THEN
    RAISE EXCEPTION 'Journal entry not found' USING ERRCODE = 'P0002';
  END IF;

  IF selected_entry.status <> 'published' OR selected_entry.published_at > now() THEN
    RAISE EXCEPTION 'Only a currently published Journal entry can be featured' USING ERRCODE = '23514';
  END IF;

  UPDATE public.journal_entries
  SET featured_at = NULL
  WHERE featured_at IS NOT NULL AND id <> target_id;

  UPDATE public.journal_entries
  SET featured_at = now()
  WHERE id = target_id
  RETURNING * INTO selected_entry;

  RETURN selected_entry;
END;
$$;

CREATE OR REPLACE FUNCTION public.reorder_journal_media(target_entry_id uuid, ordered_ids uuid[])
RETURNS SETOF public.journal_media
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Administrator access required' USING ERRCODE = '42501';
  END IF;

  IF cardinality(ordered_ids) IS NULL OR cardinality(ordered_ids) = 0 THEN
    RAISE EXCEPTION 'Media order cannot be empty' USING ERRCODE = '23514';
  END IF;

  IF (SELECT count(DISTINCT id) FROM unnest(ordered_ids) AS id) <> cardinality(ordered_ids) THEN
    RAISE EXCEPTION 'Media order contains duplicate ids' USING ERRCODE = '23514';
  END IF;

  IF (
    SELECT count(*) FROM public.journal_media WHERE entry_id = target_entry_id
  ) <> cardinality(ordered_ids)
  OR EXISTS (
    SELECT 1
    FROM unnest(ordered_ids) AS requested(id)
    LEFT JOIN public.journal_media media
      ON media.id = requested.id AND media.entry_id = target_entry_id
    WHERE media.id IS NULL
  ) THEN
    RAISE EXCEPTION 'Media order must contain every entry media id exactly once' USING ERRCODE = '23514';
  END IF;

  UPDATE public.journal_media media
  SET sort_order = requested.ordinality - 1
  FROM unnest(ordered_ids) WITH ORDINALITY AS requested(id, ordinality)
  WHERE media.id = requested.id AND media.entry_id = target_entry_id;

  RETURN QUERY
  SELECT * FROM public.journal_media
  WHERE entry_id = target_entry_id
  ORDER BY sort_order;
END;
$$;

